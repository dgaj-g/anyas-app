#!/usr/bin/env node
/* Builds js/wordmark-data.js: the pen strokes for "Anya's App".
   Source: EMS Allure (single-line script, SIL OFL, from gitlab.com/oskay/svg-fonts),
   kept at tools/fonts-src/EMSAllure.svg. The font's strokes are coarse polylines, so each
   stroke is smoothed into curves; sharp turns (the pen reversing) stay sharp.
   Run: node tools/make-wordmark.js */
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
const src = fs.readFileSync(path.join(__dirname, 'fonts-src', 'EMSAllure.svg'), 'utf8');

const TEXT = "Anya's App";
const SPACE = 300;          // word gap in font units
const TRACK = -6;           // letters sit a touch closer so the joins meet
const CUSP_DEG = 100;       // a turn sharper than this keeps its corner

const glyphs = {};
for (const m of src.matchAll(/<glyph\s+unicode="([^"]+)"[^>]*?horiz-adv-x="([\d.]+)"(?:\s+d="([^"]*)")?/g)) {
  let ch = m[1];
  if (ch === '&apos;') ch = "'";
  if (ch.length !== 1 || glyphs[ch]) continue;
  glyphs[ch] = { adv: parseFloat(m[2]), d: m[3] || '' };
}

function polylines(d) {
  const out = []; let cur = null;
  const t = d.trim().split(/\s+/);
  for (let i = 0; i < t.length;) {
    const c = t[i];
    if (c === 'M') { cur = [[+t[i + 1], +t[i + 2]]]; out.push(cur); i += 3; }
    else if (c === 'L') { cur.push([+t[i + 1], +t[i + 2]]); i += 3; }
    else { cur.push([+t[i], +t[i + 1]]); i += 2; }
  }
  return out.filter(p => p.length > 1);
}

const sub = (a, b) => [a[0] - b[0], a[1] - b[1]];
const len = v => Math.hypot(v[0], v[1]);
function turnDeg(a, b, c) {
  const u = sub(b, a), v = sub(c, b);
  const cos = (u[0] * v[0] + u[1] * v[1]) / (len(u) * len(v) || 1);
  return Math.acos(Math.max(-1, Math.min(1, cos))) * 180 / Math.PI;
}
const f = n => (Math.round(n * 10) / 10).toString();

function smooth(pts) {
  // split into runs at cusps
  const runs = []; let run = [pts[0]];
  for (let i = 1; i < pts.length; i++) {
    run.push(pts[i]);
    if (i < pts.length - 1 && turnDeg(pts[i - 1], pts[i], pts[i + 1]) > CUSP_DEG) { runs.push(run); run = [pts[i]]; }
  }
  runs.push(run);
  let d = `M${f(pts[0][0])} ${f(pts[0][1])}`;
  for (const r of runs) {
    for (let i = 0; i < r.length - 1; i++) {
      const p0 = r[i - 1] || r[i], p1 = r[i], p2 = r[i + 1], p3 = r[i + 2] || r[i + 1];
      const c1 = [p1[0] + (p2[0] - p0[0]) / 6, p1[1] + (p2[1] - p0[1]) / 6];
      const c2 = [p2[0] - (p3[0] - p1[0]) / 6, p2[1] - (p3[1] - p1[1]) / 6];
      d += `C${f(c1[0])} ${f(c1[1])} ${f(c2[0])} ${f(c2[1])} ${f(p2[0])} ${f(p2[1])}`;
    }
  }
  return d;
}

let x = 0, word = 0; const strokes = []; let minX = 1e9, minY = 1e9, maxX = -1e9, maxY = -1e9;
for (const ch of TEXT) {
  if (ch === ' ') { x += SPACE; word++; continue; }
  const g = glyphs[ch];
  if (!g) throw new Error('No glyph for ' + ch);
  for (const pl of polylines(g.d)) {
    const pts = pl.map(([px, py]) => [px + x, -py]);   // font is y-up
    for (const [px, py] of pts) { minX = Math.min(minX, px); maxX = Math.max(maxX, px); minY = Math.min(minY, py); maxY = Math.max(maxY, py); }
    strokes.push({ ch, pts, word });
  }
  x += g.adv + TRACK;
}
const PAD = 70;
const ox = -minX + PAD, oy = -minY + PAD;
const W = Math.round(maxX - minX + PAD * 2), H = Math.round(maxY - minY + PAD * 2);
const data = {
  text: TEXT, w: W, h: H, base: Math.round(oy),
  strokes: strokes.map(s => ({ ch: s.ch, w: s.word, d: smooth(s.pts.map(([px, py]) => [px + ox, py + oy])) })),
};
const js = `/* Generated by tools/make-wordmark.js — do not edit by hand.\n   Letterforms: EMS Allure (SIL Open Font License). */\nwindow.WORDMARK = ${JSON.stringify(data)};\n`;
fs.writeFileSync(path.join(root, 'js', 'wordmark-data.js'), js);
console.log(`wordmark: ${data.strokes.length} strokes, viewBox ${W}x${H}, ${js.length} bytes`);
